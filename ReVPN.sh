}

tui_persistence_form() {
    local mode_choice
    mode_choice="$(box --title "Startup Persistence" --menu \
        "Run which mode automatically on every boot?" 12 64 2 \
        client "Join a server as a client, on startup" \
        server "Start the relay/rendezvous server, on startup" \
    )" || return 1
    PERSIST_MODE="$mode_choice"

    local default_cfg="$CONFIG_DIR/generated-${PERSIST_MODE}.yaml"
    [[ -f "$default_cfg" ]] || default_cfg="$CONFIG_DIR/${PERSIST_MODE}.yaml"
    PERSIST_CFG="$(tui_input "Startup Persistence: Config File" \
        "Path to the YAML config to load on every boot\n(a --config file saved earlier, e.g. from this menu)" \
        "$default_cfg" 11 70)" || return 1

    if [[ ! -f "$PERSIST_CFG" ]]; then
        tui_msg "Not Found" "No file at:\n\n  $PERSIST_CFG\n\nRun ${PERSIST_MODE^} once first (it saves config/generated-${PERSIST_MODE}.yaml), then come back here."
        return 1
    fi

    tui_yesno "Confirm" \
"Install as a systemd service, starting on every boot:

  Mode   : ${PERSIST_MODE}
  Config : ${PERSIST_CFG}

This writes a unit file to:
  ${CONFIG_DIR}/systemd/revpn-${PERSIST_MODE}.service

And prints the sudo commands to install + enable it
(nothing is installed system-wide without your say-so).

Proceed?" 15 70 || return 1
    return 0
}

write_persistence_unit() {
    local mode="$1" cfg="$2"
    local unit_dir="$CONFIG_DIR/systemd"
    local unit_file="$unit_dir/revpn-${mode}.service"
    mkdir -p "$unit_dir"

    cat > "$unit_file" <<EOF
[Unit]
Description=ReVPN mesh VPN (${mode} mode)
After=network-online.target
Wants=network-online.target

[Service]
ExecStart=${ENGINE_BIN} --mode ${mode} --config ${cfg}
WorkingDirectory=${SELF_DIR}
StandardOutput=journal
StandardError=journal
Restart=always
RestartSec=10

[Install]
WantedBy=multi-user.target
EOF

    if [[ "$(id -u)" -eq 0 && -n "${SUDO_UID:-}" && -n "${SUDO_GID:-}" ]]; then
        chown "${SUDO_UID}:${SUDO_GID}" "$unit_file" 2>/dev/null || true
    fi

    local install_cmds
    install_cmds="sudo cp \"$unit_file\" /etc/systemd/system/revpn-${mode}.service
sudo systemctl daemon-reload
sudo systemctl enable --now revpn-${mode}"

    if [[ -n "$TUI_TOOL" ]]; then
        tui_msg "Unit File Written" "Wrote:
  $unit_file

To install and start it on boot, run:

  ${install_cmds}"
    fi
    echo "ReVPN: wrote $unit_file"
    echo "ReVPN: to install and enable it, run:"
    echo "  $install_cmds"
}

tui_stress_form() {
    ST_CLIENTS="$(tui_input  "Stress Test: Clients"  "Simulated clients"     "$ST_CLIENTS"  10 60)" || return 1
    ST_DURATION="$(tui_input "Stress Test: Duration" "Test length, seconds"  "$ST_DURATION" 10 60)" || return 1
    ST_RATE="$(tui_input     "Stress Test: Rate"     "Packets/sec per client" "$ST_RATE"    10 60)" || return 1
    ST_SIZE="$(tui_input     "Stress Test: Size"     "Payload bytes/packet"   "$ST_SIZE"    10 60)" || return 1

    tui_yesno "Confirm" \
"Run Relay-Server Stress Test:

  Clients : ${ST_CLIENTS}
  Duration: ${ST_DURATION}s
  Rate    : ${ST_RATE} pps/client
  Size    : ${ST_SIZE} bytes

No root or TUN device needed. Proceed?" || return 1
    return 0
}

tui_main() {
    pick_tui_tool
    if [[ -z "$TUI_TOOL" ]]; then
        echo "ReVPN: No arguments given, and no TUI tool found." >&2
        echo "       Install one to get the interactive menu:" >&2
        echo "         sudo apt install whiptail   # or: sudo apt install dialog" >&2
        echo >&2
        usage
        exit 1
    fi

    while true; do
        CHOICE="$(box --title "ReVPN — Main Menu" --menu \
            "No arguments given — pick what to do (like nmtui):" 20 70 7 \
            Server        "Start this machine as the relay/rendezvous server" \
            Client        "Join a ReVPN server as a client"                  \
            Decentralized "Connect directly to a peer — no server, just a token" \
            Stress        "Stress-test the relay server (no root needed)"    \
            Persistence   "Set as startup persistence (run on every boot)"    \
            Help          "Show full --help text"                            \
            Quit          "Exit"                                             \
        )" || exit 0

        case "$CHOICE" in
            Server)
                if [[ ! -x "$ENGINE_BIN" ]]; then
                    tui_msg "Not Built" "Engine binary missing.\n\nRun ./build.sh first, then re-run ReVPN.sh."
                    continue
                fi
                tui_server_form && { clear; MODE=server; launch_server; }
                ;;
            Client)
                if [[ ! -x "$ENGINE_BIN" ]]; then
                    tui_msg "Not Built" "Engine binary missing.\n\nRun ./build.sh first, then re-run ReVPN.sh."
                    continue
                fi
                tui_client_form && { clear; MODE=client; launch_client; }
                ;;
            Decentralized)
                if [[ ! -x "$ENGINE_BIN" ]]; then
                    tui_msg "Not Built" "Engine binary missing.\n\nRun ./build.sh first, then re-run ReVPN.sh."
                    continue
                fi
                tui_decentralized_form && { clear; MODE=decentralized; launch_decentralized; }
                ;;
            Stress)
                tui_stress_form && { clear; launch_stress; }
                ;;
            Persistence)
                tui_persistence_form && { clear; write_persistence_unit "$PERSIST_MODE" "$PERSIST_CFG"; }
                ;;
            Help)
                tui_msg "ReVPN.sh --help" "$(usage)"
                ;;
            Quit|"") exit 0 ;;
        esac
    done
}

# ============================================================================
# Entry point
# ============================================================================

# --reset and --config are pulled out of the argument list first, wherever
# they appear, so the remaining flags (parsed below) still get the final
# say over anything a --config file sets.
RESET=false
CONFIG_ARG=""
_ARGS=()
while [[ $# -gt 0 ]]; do
    case "$1" in
        --reset)  RESET=true; shift ;;
        --config) CONFIG_ARG="$2"; shift 2 ;;
        *) _ARGS+=("$1"); shift ;;
    esac
done
set -- "${_ARGS[@]}"

if [[ "$RESET" == true ]]; then
    rm -f "$CONFIG_FILE"
    echo "ReVPN: saved preset cleared — using defaults"
else
    load_preset
fi

if [[ -n "$CONFIG_ARG" ]]; then
    load_yaml_config "$CONFIG_ARG"
    echo "ReVPN: loaded config $CONFIG_ARG"
fi

if [[ $# -eq 0 ]]; then
    tui_main
    exit 0
fi

while [[ $# -gt 0 ]]; do
    case "$1" in
        --server) MODE="server"; shift ;;
        --client) MODE="client"; shift ;;
        --decentralized) MODE="decentralized"; shift ;;
        --stress) MODE="stress"; shift ;;
        --help|-h) usage; exit 0 ;;
        --version) echo "ReVPN ${VERSION}"; exit 0 ;;

        --port)        PORT="$2"; PORT_SET=true; shift 2 ;;
        --workers)     WORKERS="$2"; shift 2 ;;
        --xdp-iface)   XDP_IFACE="$2"; shift 2 ;;
        --xdp-copy)    XDP_COPY=true; shift ;;

        --connect)     CONNECT="$2"; shift 2 ;;
        --vpn-ip)      VPN_IP="$2"; shift 2 ;;
        --subnet)      SUBNET="$2"; shift 2 ;;
        --node-id)     NODE_ID="$2"; shift 2 ;;
        --mtu)         MTU="$2"; shift 2 ;;
        --encrypt)     ENCRYPT="$2"; shift 2 ;;
        --relay-only)  RELAY_ONLY=true; shift ;;

        --id)          DC_ID="$2"; shift 2 ;;
        --peer-token)  DC_PEER_TOKENS+=("$2"); shift 2 ;;

        --clients)     ST_CLIENTS="$2"; shift 2 ;;
        --duration)    ST_DURATION="$2"; shift 2 ;;
        --rate)        ST_RATE="$2"; shift 2 ;;
        --size)        ST_SIZE="$2"; shift 2 ;;
        --stress-port) ST_PORT="$2"; shift 2 ;;

        *) fail "unknown option '$1' (see: ReVPN.sh --help)" ;;
    esac
done

[[ -z "$MODE" ]] && { usage; fail "one of --server, --client, --decentralized or --stress is required"; }

case "$MODE" in
    server)        launch_server ;;
    client)        launch_client ;;
    decentralized) launch_decentralized ;;
    stress)        launch_stress ;;
esac
