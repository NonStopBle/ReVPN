#!/usr/bin/env bash
# ============================================================================
# ReVPN — Hamachi-style CLI + nmtui-style TUI for the mesh VPN engine
#         (TUN + UDP hole punch + auto relay fallback + XDP zero-copy).
#
# The heavy lifting (TUN device, UDP hole punching, relay fallback, XDP)
# is all done by the compiled `ReVPN-engine` binary (built from meshvpn.cpp
# under engine/). This script is a friendly CLI in front of it, and — when
# run with no arguments at all — a full-screen interactive TUI, the same
# way `nmtui` is the no-argument counterpart to `nmcli`.
# ============================================================================
set -euo pipefail

SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENGINE_BIN="$SELF_DIR/build/ReVPN-engine"
STRESS_BIN="$SELF_DIR/tools/stress_client.py"

VERSION="1.0.2"

# ── Defaults (Hamachi-like: sane out of the box) ───────────────────────────
PORT=9000            # server bind port / client local udp port base
PORT_SET=false
WORKERS=4            # server worker threads
VPN_IP=""
CONNECT=""           # server address to join, ip:port
SUBNET=16
MTU=1380
NODE_ID=""
ENCRYPT=true
XDP_IFACE=""
XDP_COPY=false
RELAY_ONLY=false
MODE=""

# Decentralized-mode defaults (no server — direct token exchange)
DC_ID=""
DC_PEER_TOKENS=()

# Stress-test defaults
ST_CLIENTS=20
ST_DURATION=10
ST_RATE=500
ST_SIZE=512
ST_PORT=19099

fail() { echo "ReVPN: $*" >&2; exit 1; }

# ============================================================================
# Preset — last-used settings, saved after every successful launch and
# reloaded as the new defaults next time (server/client/stress separately,
# so switching modes doesn't clobber each other's fields). `ReVPN.sh --reset`
# deletes it and falls back to the hardcoded defaults above.
# ============================================================================
# Saved inside this checkout's own config/ directory (next to
# server.yaml/client.yaml), not under the user's home — ReVPN.sh stays
# fully self-contained in wherever it's checked out. ReVPN needs root for
# --server/--client (TUN device, raw sockets), so a `sudo ./ReVPN.sh
# --client ...` run would otherwise leave this file root-owned, and a
# later plain `./ReVPN.sh` (as the normal user) couldn't rewrite it —
# ownership is handed back to the invoking user in save_preset() below.
CONFIG_DIR="$SELF_DIR/config"
CONFIG_FILE="$CONFIG_DIR/preset.conf"

load_preset() {
    # shellcheck disable=SC1090
    [[ -f "$CONFIG_FILE" ]] && source "$CONFIG_FILE"
    return 0
}

save_preset() {
    mkdir -p "$CONFIG_DIR"
    cat > "$CONFIG_FILE" <<EOF
# ReVPN saved preset — last settings used, reloaded automatically.
# Delete this file, or run: ReVPN.sh --reset
PORT=${PORT}
PORT_SET=${PORT_SET}
WORKERS=${WORKERS}
XDP_IFACE="${XDP_IFACE}"
XDP_COPY=${XDP_COPY}
VPN_IP="${VPN_IP}"
CONNECT="${CONNECT}"
SUBNET=${SUBNET}
MTU=${MTU}
NODE_ID="${NODE_ID}"
ENCRYPT=${ENCRYPT}
RELAY_ONLY=${RELAY_ONLY}
ST_CLIENTS=${ST_CLIENTS}
ST_DURATION=${ST_DURATION}
ST_RATE=${ST_RATE}
ST_SIZE=${ST_SIZE}
ST_PORT=${ST_PORT}
DC_ID="${DC_ID}"
EOF
    # Hand ownership back to the real user when we're running under sudo,
    # so their own later non-sudo `./ReVPN.sh` can read AND rewrite it.
    if [[ "$(id -u)" -eq 0 && -n "${SUDO_UID:-}" && -n "${SUDO_GID:-}" ]]; then
        chown -R "${SUDO_UID}:${SUDO_GID}" "$CONFIG_DIR" 2>/dev/null || true
    fi
}

# ============================================================================
# Also write a real YAML file the engine itself can load with --config —
# same flat "key: value" format and keys as config/server.yaml /
# config/client.yaml, generated fresh from whatever mode was just
# launched. This is what lets a run you tried through the TUI or flags
# here turn straight into a `ReVPN-engine --config <file>` invocation for
# a systemd unit, Docker container, or anything else that shouldn't
# depend on this script. Peer tokens are one-time secrets and are never
# written here, same as they're never saved to the preset either.
# ============================================================================
save_yaml_config() {
    local mode="$1" out="$CONFIG_DIR/generated-${1}.yaml"
    mkdir -p "$CONFIG_DIR"
    local port_val=""
    [[ "$PORT_SET" == true ]] && port_val="$PORT"

    case "$mode" in
        server)
            cat > "$out" <<EOF
# Generated by ReVPN.sh — matches the server just launched.
# Load directly with: $ENGINE_BIN --mode server --config $out
port: ${PORT}
workers: ${WORKERS}
xdp_iface: "${XDP_IFACE}"
xdp_copy: ${XDP_COPY}
vpn_ip: "${VPN_IP}"
subnet: ${SUBNET}
mtu: ${MTU}
EOF
            ;;
        client)
            cat > "$out" <<EOF
# Generated by ReVPN.sh — matches the client just launched.
# Load directly with: $ENGINE_BIN --mode client --config $out
connect: "${CONNECT}"
vpn_ip: "${VPN_IP}"
subnet: ${SUBNET}
port: ${port_val}
node_id: "${NODE_ID}"
mtu: ${MTU}
encrypt: ${ENCRYPT}
relay_only: ${RELAY_ONLY}
EOF
            ;;
        decentralized)
            cat > "$out" <<EOF
# Generated by ReVPN.sh — matches the decentralized node just launched.
# Peer tokens are one-time secrets and are never saved here — pass them
# with --peer-token (repeatable) alongside --config when you load this.
# Load directly with: $ENGINE_BIN --mode decentralized --config $out --peer-token <token>
id: "${DC_ID}"
vpn_ip: "${VPN_IP}"
subnet: ${SUBNET}
port: ${port_val}
mtu: ${MTU}
encrypt: ${ENCRYPT}
EOF
            ;;
        *) return 0 ;;
    esac

    if [[ "$(id -u)" -eq 0 && -n "${SUDO_UID:-}" && -n "${SUDO_GID:-}" ]]; then
        chown "${SUDO_UID}:${SUDO_GID}" "$out" 2>/dev/null || true
    fi
    echo "ReVPN: wrote $out"
}

# ============================================================================
# --config <file> — flat "key: value" YAML, one file for --server settings
# (config/server.yaml) and one for --client settings (config/client.yaml).
# Only simple scalars are supported (no nesting/lists) — that's all these
# settings need. Values here override the saved preset but are themselves
# overridden by any matching flag also given on the command line.
# ============================================================================
load_yaml_config() {
    local f="$1"
    [[ -f "$f" ]] || fail "config file not found: $f"

    local line key val
    while IFS= read -r line || [[ -n "$line" ]]; do
        line="${line%%#*}"                               # strip comments
        line="$(sed 's/^[[:space:]]*//;s/[[:space:]]*$//' <<<"$line")"
        [[ -z "$line" ]] && continue
        [[ "$line" != *:* ]] && continue

        key="${line%%:*}"
        val="${line#*:}"
        key="$(sed 's/[[:space:]]*$//' <<<"$key")"
        val="$(sed 's/^[[:space:]]*//;s/[[:space:]]*$//;s/^"//;s/"$//;s/^'"'"'//;s/'"'"'$//' <<<"$val")"

        case "$key" in
            port)          [[ -n "$val" ]] && { PORT="$val"; PORT_SET=true; } ;;
            workers)       WORKERS="$val" ;;
            xdp_iface)     XDP_IFACE="$val" ;;
            xdp_copy)      XDP_COPY="$val" ;;
            connect)       CONNECT="$val" ;;
            vpn_ip)        VPN_IP="$val" ;;
            subnet)        SUBNET="$val" ;;
            node_id)       NODE_ID="$val" ;;
            mtu)           MTU="$val" ;;
            encrypt)       ENCRYPT="$val" ;;
            relay_only)    RELAY_ONLY="$val" ;;
            clients)       ST_CLIENTS="$val" ;;
            duration)      ST_DURATION="$val" ;;
            rate)          ST_RATE="$val" ;;
            size)          ST_SIZE="$val" ;;
            stress_port)   ST_PORT="$val" ;;
            *) ;; # ignore unknown keys
        esac
    done < "$f"
}

