                       at this VPN IP (default: pure bridge, no TUN)
  --subnet <n>         VPN network prefix length, with --vpn-ip (default: ${SUBNET})
  --xdp-iface <if>    Enable AF_XDP zero-copy on interface   (e.g. eth0)
                       Only works if built with: ./build.sh --xdp
  --xdp-copy          Force XDP copy-mode (compat, slower)

CLIENT OPTIONS:
  --connect <ip:port>  Address of the ReVPN server to join    (required)
  --vpn-ip <ip>        This node's VPN IP, e.g. 10.13.0.2      (required)
  --subnet <n>         VPN network prefix length              (default: ${SUBNET})
  --port <n>           Local UDP port                          (default: 51820)
  --node-id <hex>      Fixed 32-bit node id (default: derived from --vpn-ip)
  --mtu <n>            TUN interface MTU                       (default: ${MTU})
  --encrypt <true|false>  Encrypt tunnel traffic               (default: ${ENCRYPT})
