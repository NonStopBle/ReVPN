  — no flag needed. Use --relay-only to skip punching entirely.

DECENTRALIZED OPTIONS:
  --id <name>          Your display name in the token                (required)
  --vpn-ip <ip>        This node's VPN IP, e.g. 10.13.0.2             (required)
  --subnet <n>         VPN network prefix length              (default: ${SUBNET})
  --port <n>           Local UDP port                          (default: 51001)
