require_engine() {
    [[ -x "$ENGINE_BIN" ]] || fail "engine binary not built yet — run: $SELF_DIR/build.sh"
}

# ============================================================================
# Launchers — shared by both the flag-based CLI and the TUI below.
# ============================================================================
launch_server() {
    require_engine
    local args=(--mode server --bind "0.0.0.0:${PORT}" --workers "${WORKERS}")
    [[ -n "$XDP_IFACE" ]] && args+=(--xdp-iface "$XDP_IFACE")
    [[ "$XDP_COPY" == true ]] && args+=(--xdp-copy)
    [[ -n "$VPN_IP" ]] && args+=(--vpn-ip "$VPN_IP" --subnet "$SUBNET" --mtu "$MTU")

    if [[ -n "$VPN_IP" ]]; then
        echo "ReVPN: starting server on 0.0.0.0:${PORT} (${WORKERS} workers), joining mesh as ${VPN_IP}/${SUBNET}"
    else
        echo "ReVPN: starting server on 0.0.0.0:${PORT} (${WORKERS} workers)"
    fi
    save_preset
    save_yaml_config server
    exec "$ENGINE_BIN" "${args[@]}"
}

launch_client() {
    require_engine
    [[ -n "$VPN_IP" ]]  || fail "--client requires --vpn-ip <ip>"
    [[ -n "$CONNECT" ]] || fail "--client requires --connect <ip:port>"
    case "$ENCRYPT" in
        true|false) ;;
        *) fail "--encrypt must be 'true' or 'false' (got: $ENCRYPT)" ;;
    esac

    local comm="p2p"
    [[ "$RELAY_ONLY" == true ]] && comm="relay"

    local args=(--mode client --vpn-ip "$VPN_IP" --server "$CONNECT" --comm "$comm"
                --subnet "$SUBNET" --mtu "$MTU")
    [[ -n "$NODE_ID" ]] && args+=(--node-id "$NODE_ID")
    [[ "$PORT_SET" == true ]] && args+=(--port "$PORT")
    [[ "$ENCRYPT" == "false" ]] && args+=(--no-encrypt)

    echo "ReVPN: joining ${CONNECT} as ${VPN_IP}/${SUBNET}  (mode=${comm}, encrypt=${ENCRYPT})"
    [[ "$comm" == "p2p" ]] && echo "ReVPN: will try direct UDP hole punching, auto-relay on failure"
    save_preset
    save_yaml_config client
    exec "$ENGINE_BIN" "${args[@]}"
}

launch_stress() {
    require_engine
    command -v python3 >/dev/null 2>&1 || fail "--stress needs python3"
    save_preset
    exec "$SELF_DIR/stress_test.sh" \
        --port "$ST_PORT" --clients "$ST_CLIENTS" \
        --duration "$ST_DURATION" --rate "$ST_RATE" --size "$ST_SIZE"
}

launch_decentralized() {
    require_engine
    [[ -n "$VPN_IP" ]] || fail "--decentralized requires --vpn-ip <ip>"
    [[ -n "$DC_ID" ]]  || fail "--decentralized requires --id <name>"
    case "$ENCRYPT" in
        true|false) ;;
        *) fail "--encrypt must be 'true' or 'false' (got: $ENCRYPT)" ;;
    esac

    local args=(--mode decentralized --id "$DC_ID" --vpn-ip "$VPN_IP"
                --subnet "$SUBNET" --mtu "$MTU")
    [[ "$PORT_SET" == true ]] && args+=(--port "$PORT")
    for tok in "${DC_PEER_TOKENS[@]}"; do
        [[ -n "$tok" ]] && args+=(--peer-token "$tok")
    done
    [[ "$ENCRYPT" == "false" ]] && args+=(--no-encrypt)

    echo "ReVPN: decentralized mode — no server, direct token exchange with your peer(s)"
    save_preset
    save_yaml_config decentralized
    exec "$ENGINE_BIN" "${args[@]}"
}

# ============================================================================
# TUI — nmtui-style full-screen menu, shown automatically when ReVPN.sh is run
# with NO arguments at all. Uses whiptail (or dialog as a fallback); both
# are the same libnewt-family tool nmtui itself is built on.
# ============================================================================
TUI_TOOL=""
pick_tui_tool() {
    if command -v whiptail >/dev/null 2>&1; then TUI_TOOL="whiptail"
    elif command -v dialog >/dev/null 2>&1;   then TUI_TOOL="dialog"
    else TUI_TOOL=""
    fi
}

# box <height> <width> -- <mode-specific-args...>
box() { "$TUI_TOOL" --backtitle "ReVPN ${VERSION} — Mesh VPN — Creative By Rezier Labs" "$@" 3>&1 1>&2 2>&3; }

tui_input() { # title text default height width
    box --title "$1" --inputbox "$2" "$4" "$5" "$3"
}

tui_yesno() { # title text [height] [width] -> 0=yes 1=no
    "$TUI_TOOL" --backtitle "ReVPN ${VERSION} — Mesh VPN — Creative By Rezier Labs" \
        --title "$1" --yesno "$2" "${3:-10}" "${4:-60}"
}

tui_msg() {
    "$TUI_TOOL" --backtitle "ReVPN ${VERSION} — Mesh VPN — Creative By Rezier Labs" \
        --title "$1" --msgbox "$2" 16 70
}

xdp_supported() { [[ -f "$SELF_DIR/build/.xdp_enabled" ]]; }

# Real network interfaces on this machine (excludes loopback), for the
# AF_XDP picker below — never free-typed, always chosen from what exists.
list_interfaces() {
    ip -o link show 2>/dev/null \
        | awk -F': ' '{print $2}' \
        | sed 's/@.*//' \
        | grep -v '^lo$' \
        || true
}

tui_pick_xdp_iface() {
    local ifaces=()
    while IFS= read -r ifn; do
        [[ -n "$ifn" ]] && ifaces+=("$ifn" "Enable AF_XDP zero-copy on $ifn")
    done < <(list_interfaces)

    if [[ ${#ifaces[@]} -eq 0 ]]; then
        tui_msg "AF_XDP" "No network interfaces were found to pick from.\n\nContinuing without AF_XDP (recvmmsg)."
        XDP_IFACE=""
        return 0
    fi

    local choice
    choice="$(box --title "Server: AF_XDP Interface" --menu \
        "Pick a NIC for zero-copy AF_XDP, or None to use recvmmsg:" \
        $(( ${#ifaces[@]} / 2 + 9 )) 64 $(( ${#ifaces[@]} / 2 + 1 )) \
        None "Disable AF_XDP (use recvmmsg)" \
        "${ifaces[@]}")" || return 1

    [[ "$choice" == "None" ]] && XDP_IFACE="" || XDP_IFACE="$choice"
    return 0
}

tui_server_form() {
    PORT="$(tui_input "Server: UDP Port"     "Port to listen on"        "$PORT"    10 60)"    || return 1
    WORKERS="$(tui_input "Server: Workers"    "Worker threads"           "$WORKERS" 10 60)"    || return 1

    if xdp_supported; then
        tui_pick_xdp_iface || return 1
    else
        XDP_IFACE=""
    fi
    PORT_SET=true

    if tui_yesno "Server as peer" \
"Also join the mesh yourself, so clients can reach
this server machine at its own VPN IP (not just
relay/rendezvous for each other)?

(Linux only — needs root, same as a client's TUN.)"; then
        VPN_IP="$(tui_input "Server: VPN IP" "This server's VPN IP, e.g. 10.13.0.1" "${VPN_IP:-10.13.0.1}" 10 60)" || return 1
        SUBNET="$(tui_input "Server: Subnet Prefix" "VPN network prefix length" "$SUBNET" 10 60)" || return 1
    else
        VPN_IP=""
    fi

    tui_yesno "Confirm" \
"Start Server (relay / rendezvous):

  Port     : ${PORT}
  Workers  : ${WORKERS}
  XDP Iface: ${XDP_IFACE:-None}
  VPN IP   : $([[ -n "$VPN_IP" ]] && echo "${VPN_IP}/${SUBNET}  (server joins as a peer)" || echo "None (pure bridge)")

Proceed?" 13 60 || return 1
    return 0
}

tui_client_form() {
    CONNECT="$(tui_input "Client: Server Address" "Address of the server to join, ip:port" "$CONNECT" 10 60)" || return 1
    VPN_IP="$(tui_input  "Client: VPN IP"          "This node's VPN IP, e.g. 10.13.0.2" "${VPN_IP:-10.13.0.2}" 10 60)" || return 1
    SUBNET="$(tui_input  "Client: Subnet Prefix"   "VPN network prefix length" "$SUBNET" 10 60)" || return 1

    if tui_yesno "Encryption" "Encrypt tunnel traffic?"; then ENCRYPT=true; else ENCRYPT=false; fi

    if tui_yesno "Hole Punching" \
"Try direct UDP hole punching between peers first,
And automatically fall back to relaying through
The server if punching fails?

(Choose 'No' to force relay-only.)"; then
        RELAY_ONLY=false
    else
        RELAY_ONLY=true
    fi

    tui_yesno "Confirm" \
"Join as Client:

  Server   : ${CONNECT}
  VPN IP   : ${VPN_IP}/${SUBNET}
  Encrypt  : ${ENCRYPT}
  Mode     : $([[ "$RELAY_ONLY" == true ]] && echo "Relay-only" || echo "P2P + auto relay fallback")

Proceed?" || return 1
    return 0
}

