    VPN_IP="$(tui_input "Decentralized: VPN IP" "This node's VPN IP, e.g. 10.13.0.2" "${VPN_IP:-10.13.0.2}" 10 60)" || return 1
    SUBNET="$(tui_input "Decentralized: Subnet Prefix" "VPN network prefix length" "$SUBNET" 10 60)" || return 1

